#!/usr/bin/env bash
# Writes docs/history/changelog.md from the git log of this branch.
# Run through `npm run gen`; safe to run twice, the output is byte-identical.
set -euo pipefail
cd "$(dirname "$0")/../.."

out=docs/history/changelog.md
mkdir -p "$(dirname "$out")"

{
	printf -- '---\n'
	printf -- 'title: Changelog\n'
	printf -- 'description: Every commit on this branch, newest first, generated from git log.\n'
	printf -- '---\n\n'
	printf -- 'This page is generated by `website/scripts/gen-changelog.sh`; an edit made here is\n'
	printf -- 'reverted by the next run.\n\n'
	printf -- '<!-- BEGIN GENERATED: changelog -->\n'
	# The changelog's own commit must not change the next run's output.
	git log --no-merges --pretty='- %s (%h)' -- . ":(exclude)${out}"
	printf -- '<!-- END GENERATED: changelog -->\n'
} >"$out"

echo "wrote $out"
